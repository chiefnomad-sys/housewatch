"""Builds the inline logo paths used by the site (src/data/marks.ts) from the v4 logo sources.
Run: python3 tools/make_marks.py <path to logo/v4/source>"""
import sys, json, os
sys.path.insert(0, sys.argv[1])
from hwlib import text, measure
from icons import icon
AN = 'Anton-Regular.ttf'; PI = 'PirataOne-Regular.ttf'
CAP = 1760 / 2048
size = 200; tr = size * 0.01; base = 200
_, w1, _ = measure(AN, 'HOUSE', size, tr); _, w2, _ = measure(AN, 'WATCH', size, tr)
gap = 0.08 * size; iw = 0.8 * size
tot = w1 + gap + iw + gap + w2
x = 0
d1, _ = text(AN, 'HOUSE', x, base, size, tr, anchor='start')
d2, _ = text(AN, 'WATCH', x + w1 + 2 * gap + iw, base, size, tr, anchor='start')
ic = icon('irons', x + w1 + gap + iw / 2, base - CAP * size / 2, iw / 1.28, 'currentColor', 'none')
top = base - CAP * size
word = {'viewBox': f'0 {top - 4:.1f} {tot:.1f} {CAP*size + 8:.1f}', 'house': d1, 'watch': d2, 'irons': ic}
# Gothic H with the bar under it, on a transparent ground
S = 512
h, _ = text(PI, 'H', S/2, 372, 400)
hmark = {'viewBox': '96 40 320 400', 'h': h, 'bar': {'x': 126, 'y': 410, 'w': 260, 'h': 22}}
out = 'src/data/marks.ts'
with open(out, 'w') as f:
    f.write('// Generated by tools/make_marks.py from the v4 logo set. Do not edit by hand.\n')
    f.write('export const WORDMARK = ' + json.dumps(word) + ' as const;\n')
    f.write('export const HMARK = ' + json.dumps(hmark) + ' as const;\n')
print(word['viewBox'], len(d1), len(h))
